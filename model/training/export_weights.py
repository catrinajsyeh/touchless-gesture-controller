"""Write int8 weights into the firmware translation unit."""

from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_CPP = ROOT / "firmware" / "src" / "gesture_recognition" / "model_weights.cpp"


def quantize(array):
    peak = float(np.max(np.abs(array))) if array.size else 0.0
    if peak < 1e-8:
        return np.zeros(array.shape, dtype=np.int8), 1.0
    scale = peak / 127.0
    quantized = np.clip(np.round(array / scale), -127, 127).astype(np.int8)
    return quantized, float(scale)


def dequantize(quantized, scale):
    return quantized.astype(np.float32) * np.float32(scale)


def _format_i8(values):
    numbers = [str(int(v)) for v in values.reshape(-1)]
    lines = []
    for start in range(0, len(numbers), 18):
        lines.append("    " + ", ".join(numbers[start : start + 18]))
    return ",\n".join(lines)


def _array(name, quantized, scale):
    count = int(quantized.size)
    if count == 0:
        body = "0"
        count = 0
    else:
        body = _format_i8(quantized)
    return (
        f"const int {name}Count = {count};\n"
        f"const int8_t {name}q[] = {{\n{body}\n}};\n"
        f"const float {name}Scale = {scale:.8g}f;\n"
    )


def checksum(parts):
    total = 0
    for part in parts:
        total = (total + int(part.astype(np.int64).sum())) & 0xFFFFFFFF
    return total


def write_cpp(path, weights, trained, domain):
    names = ["kW1", "kB1", "kW2", "kB2", "kW3", "kB3", "kWd", "kBd"]
    quantized = []
    scales = []
    for weight in weights:
        q, scale = quantize(np.asarray(weight, dtype=np.float32))
        quantized.append(q)
        scales.append(scale)
    check = checksum(quantized) if trained else 0
    chunks = []
    for name, q, scale in zip(names, quantized, scales):
        chunks.append(_array(name, q if trained else np.zeros(0, dtype=np.int8), scale if trained else 1.0))
    text = f"""#include "gesture_recognition/model_weights.h"

// Generated by model/training/export_weights.py
// domain: {domain}

const bool kModelTrained = {"true" if trained else "false"};
const char kModelDomain[] = "{domain}";
const uint32_t kModelChecksum = {check}u;
const float kInputScale = {1.0 / 127.5:.8g}f;
const float kInputBias = -1.0f;

{"".join(chunks)}"""
    Path(path).write_text(text, encoding="utf-8")
    return {
        "checksum": check,
        "float_bytes": int(sum(np.asarray(w).nbytes for w in weights)),
        "int8_bytes": int(sum(q.nbytes for q in quantized)) if trained else 0,
        "quantized": quantized,
        "scales": scales,
    }
